import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../../', import.meta.url)
const output = new URL('supabase/functions/tone_completion_probe/', root)
const read = (file) => readFileSync(new URL(file, root), 'utf8').replace(/\r\n/g, '\n')
const hash = (text) => createHash('sha256').update(text).digest('hex')
mkdirSync(output, { recursive: true })
for (const [variant, file] of Object.entries({
  before: 'supabase/live-functions/correct/correct/index.ts',
  after: 'supabase/functions/correct/index.ts',
})) {
  const source = read(file)
  assert.equal((source.match(/^import .*$/gm) ?? []).length, 4)
  assert.equal((source.match(/Deno\.serve\(/g) ?? []).length, 1)
  const body = source.replace(/^import .*$/gm, '').replace('Deno.serve(', 'const handler = (')
  const edits = read('supabase/functions/correct/proofing_edits.ts').replace(/^export /gm, '')
  writeFileSync(new URL(`generated-${variant}.ts`, output), `// Generated by scripts/supabase/prepare-tone-probe.mjs. Do not edit.
export const sourceSha256 = '${hash(source)}'
export function createPipeline(fetch: typeof globalThis.fetch, geminiKey: string) {
  const metrics = { wallet: 0, charge: 0, refund: 0 }
  const console = { log: (..._args: unknown[]) => {}, warn: (..._args: unknown[]) => {}, error: (..._args: unknown[]) => {} }
  const Deno = { env: { get: (name: string) => name === 'GEMINI_API_KEY' ? geminiKey : undefined } }
  class WalletAccessError extends Error { status: number; constructor(message: string, status: number) { super(message); this.status = status } }
  const createClient = (..._args: unknown[]) => ({ from: () => { throw new Error('DATABASE_FORBIDDEN') } })
  const resolveCreditWallet = async (_req: Request, _client: unknown, walletId: string) => {
    if (walletId !== 'synthetic-tone-only') throw new Error('REAL_WALLET_FORBIDDEN')
    metrics.wallet++; return { walletId }
  }
  const consumeAIUsage = async (_client: unknown, walletId: string, _id: string, kind: string) => {
    if (walletId !== 'synthetic-tone-only' || kind !== 'formal') throw new Error('REAL_CREDIT_FORBIDDEN')
    metrics.charge++; return { accepted: true, alreadyProcessed: false, freeCredits: 0, paidCredits: 0, remaining: 0 }
  }
  const refundAIUsage = async (..._args: unknown[]) => { metrics.refund++ }
${edits}
${body}
  return { handler, metrics }
}
`)
}
console.log('Prepared two exact correction handlers with simulated wallet/credit boundaries; no network calls.')
